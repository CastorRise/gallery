export function pagePath(pathname: string): string {
  return pathname
    .replace(/^\/gallery\/?/, '')
    .replace(/^(zh-tw|zh|ja)(\/|$)/, '');
}
export function localeFromPath(pathname: string): Locale {
  const first = pathname.replace(/^\/gallery\/?/, '').split('/')[0];
  return locales.includes(first as Locale) && first !== 'en'
    ? (first as Locale)
    : 'en';
}
export function localizedUrl(path: string, locale: Locale): string {
  return `/gallery/${locale === 'en' ? '' : `${locale}/`}${path.replace(/^\//, '')}`;
}
